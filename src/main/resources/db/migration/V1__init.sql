-- paymentsflow initial schema (PostgreSQL, `postgres` profile).
-- The dev/test profile uses H2 with Hibernate-generated DDL, so this migration
-- is only applied in production, where Hibernate runs with ddl-auto=validate.

CREATE TABLE account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(255)   NOT NULL,
    type          VARCHAR(16)    NOT NULL,
    currency      VARCHAR(3)     NOT NULL,
    balance_minor BIGINT         NOT NULL,
    version       BIGINT         NOT NULL,
    created_at    TIMESTAMPTZ    NOT NULL,
    CONSTRAINT chk_account_type
        CHECK (type IN ('ASSET', 'LIABILITY', 'EQUITY', 'INCOME', 'EXPENSE'))
);

CREATE TABLE journal_entry (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency    VARCHAR(3)   NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL
);

CREATE TABLE posting (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journal_entry_id BIGINT      NOT NULL,
    account_id       BIGINT      NOT NULL,
    direction        VARCHAR(6)  NOT NULL,
    amount_minor     BIGINT      NOT NULL,
    CONSTRAINT fk_posting_journal_entry
        FOREIGN KEY (journal_entry_id) REFERENCES journal_entry (id),
    CONSTRAINT fk_posting_account
        FOREIGN KEY (account_id) REFERENCES account (id),
    CONSTRAINT chk_posting_direction
        CHECK (direction IN ('DEBIT', 'CREDIT')),
    CONSTRAINT chk_posting_amount_positive
        CHECK (amount_minor > 0)
);

CREATE INDEX idx_posting_journal_entry ON posting (journal_entry_id);
CREATE INDEX idx_posting_account ON posting (account_id);

-- One row per client idempotency key; the primary key makes a replay a failed
-- insert, which the service turns into "return the original result".
CREATE TABLE idempotency_record (
    idempotency_key  VARCHAR(255) PRIMARY KEY,
    journal_entry_id BIGINT      NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL,
    CONSTRAINT fk_idempotency_journal_entry
        FOREIGN KEY (journal_entry_id) REFERENCES journal_entry (id)
);
